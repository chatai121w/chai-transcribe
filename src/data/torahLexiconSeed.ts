export type TorahLexiconSeedEntry = {
  term: string;
  category: 'tractate' | 'tanna' | 'amora' | 'commentator' | 'aramaic' | 'rabbinic_book' | 'concept';
  variants?: string[];
  pronunciation?: string;
  contextTags?: string[];
};

function entries(
  category: TorahLexiconSeedEntry['category'],
  terms: readonly string[],
  contextTags: string[] = [],
): TorahLexiconSeedEntry[] {
  return terms.map((term) => ({ term, category, contextTags }));
}

