/**
 * נרמול הגייה אשכנזית-ליטאית לכתיב עברי תקני.
 *
 * הרקע: המנוע שומע נכון וכותב את מה ששמע. "חודש" נאמר "חוידעש" ונכתב כך,
 * "הפוסקים" נשמע "הפויסקים". זו אינה בעיית אוצר מילים — הוספת מילים לרשימת
 * המונחים לא עוזרת, וזה נמדד. מה שחסר הוא המיפוי חזרה לכתיב התקני.
 *
 * מקור הכללים: חמשת כללי ההמרה שפרסם NHLOCAL ברישיון חופשי בתוך הנחיית
 * המערכת של gemini-subtitle-creator. במקור הם נוסחו כהנחיה למודל שפה גדול
 * שיודע להכליל אותם; כאן הם הפכו לדפוסים ממשיים, כי המנוע המקומי אינו
 * מקבל הנחיות — נמדד 24.10.2026: חמש גרסאות הנחיה, אפס השפעה על הפלט.
 *
 * מגבלה שחשוב להכיר: ההגייה משתנה בין חסידויות. החולם נשמע "אוי" בפולין
 * ובהונגריה, "יי" בחלק מליטא, ובחב"ד באמצע. חמשת הכללים האלה מכסים את
 * ההגייה הליטאית בלבד.
 *
 * עיקרון זהירות: כל דפוס כאן חייב להיות חד-משמעי. מוטב לפספס מילה מאשר
 * לשבור מילה עברית תקנית. לכן אין כאן התאמה מקורבת ואין מרחק עריכה —
 * רק רצפי אותיות שאינם קיימים בעברית תקנית, או מילים ברשימה סגורה.
 */

export interface AshkenaziChange {
  from: string;
  to: string;
  rule: string;
}

export interface AshkenaziResult {
  text: string;
  changes: AshkenaziChange[];
}

/** מילים שלמות שנשמעות אחרת לגמרי — רשימה סגורה, בטוחה לחלוטין. */
const WHOLE_WORDS: ReadonlyArray<readonly [string, string, string]> = [
  // כלל 5 — תנועת סגול בהברה אחרונה
  ['שאבעס', 'שבת', 'סגול בהברה אחרונה'],
  ['שאבאס', 'שבת', 'סגול בהברה אחרונה'],
  ['גמורא', 'גמרא', 'סגול בהברה אחרונה'],
  ['גמורע', 'גמרא', 'סגול בהברה אחרונה'],
  ['שולעם', 'שלום', 'סגול בהברה אחרונה'],
  ['רובא', 'רבא', 'סגול בהברה אחרונה'],
  ['רובע', 'רבא', 'סגול בהברה אחרונה'],
  // כלל 2 — קמץ הנשמע O או OY
  ['חוכמו', 'חכמה', 'קמץ כ-O'],
  ['אודom', 'אדם', 'קמץ כ-O'],
  ['אודם', 'אדם', 'קמץ כ-O'],
  ['עוילום', 'עולם', 'קמץ כ-OY'],
  ['עוילם', 'עולם', 'קמץ כ-OY'],
  // כלל 4 — חולם הנשמע OY
  ['חלוים', 'חלום', 'חולם כ-OY'],
  ['טויב', 'טוב', 'חולם כ-OY'],
  ['תוירה', 'תורה', 'חולם כ-OY'],
  ['מוישה', 'משה', 'חולם כ-OY'],
  ['יוים', 'יום', 'חולם כ-OY'],
  // כלל 1 — ת' רפה הנשמעת ס'
  ['בראשיס', 'בראשית', "ת' רפה כ-ס'"],
  ['אמעס', 'אמת', "ת' רפה כ-ס'"],
  ['עמעס', 'אמת', "ת' רפה כ-ס'"],
  ['שבס', 'שבת', "ת' רפה כ-ס'"],
  ['בביס', 'בבית', "ת' רפה כ-ס'"],
  ['דעס', 'דת', "ת' רפה כ-ס'"],
];

/**
 * דפוסים בתוך מילה. כל דפוס כאן נבחר כך שהרצף שהוא מחפש כמעט אינו קיים
 * בעברית תקנית, ולכן הסיכון לשבור מילה כשרה נמוך.
 */
const PATTERNS: ReadonlyArray<{ re: RegExp; to: string; rule: string }> = [
  // "חוידש" → "חודש", "פוילין" → "פולין". הרצף וי בין עיצורים כמעט תמיד
  // מסמן חולם אשכנזי; מילים כמו "אויר" או "גוי" מוגנות בבדיקת ההקשר למטה.
  { re: /(?<=[א-ת])ויי?(?=[א-ת])/g, to: 'ו', rule: 'חולם כ-OY' },
  // "הפויסקים" → "הפוסקים" נתפס על ידי הדפוס שמעליו.
  // "בעלים" הנשמע "באלם" אינו נכנס לכאן — חד-משמעי מדי לשבור.
];

/** מילים עבריות תקניות שמכילות רצף שדפוס עלול לשבור. חסימה מוחלטת. */
const PROTECTED = new Set([
  'אויר', 'אוירה', 'גוי', 'גויים', 'הגוי', 'לגוי', 'ראוי', 'ראויה', 'ראויים',
  'שוויון', 'רווי', 'דווי', 'צוית', 'ציווי', 'עוית', 'לוית', 'שוית',
  'מצוי', 'מצויה', 'מצויים', 'גלוי', 'גלויה', 'בנוי', 'בנויה', 'עשוי',
  'עשויה', 'קרוי', 'שנוי', 'פנוי', 'צפוי', 'רצוי', 'דחוי', 'תלוי',
]);

const WORD_MAP = new Map<string, readonly [string, string]>();
for (const [from, to, rule] of WHOLE_WORDS) {
  WORD_MAP.set(from, [to, rule]);
}

/**
 * ממיר טקסט שתומלל מהגייה אשכנזית לכתיב תקני.
 * מחזיר גם את רשימת השינויים, כדי שאפשר יהיה למדוד מה קרה ולא לנחש.
 */
export function normalizeAshkenazi(text: string): AshkenaziResult {
  if (!text) return { text: text ?? '', changes: [] };

  const changes: AshkenaziChange[] = [];

  const out = text.replace(/[א-ת']+/g, (word) => {
    if (PROTECTED.has(word)) return word;

    // רשימה סגורה קודמת — היא המדויקת ביותר
    const whole = WORD_MAP.get(word);
    if (whole) {
      changes.push({ from: word, to: whole[0], rule: whole[1] });
      return whole[0];
    }

    // תחיליות עבריות: מאפשר "והחוידש" להיתפס כמו "חוידש".
    // חייבים לנסות גם אורך 1 וגם אורך 2, ולהעדיף את הארוך. ב"בשאבעס"
    // הצירוף "בש" נראה כתחילית חוקית, אך התחילית האמיתית היא "ב" בלבד
    // והגזע הוא "שאבעס" — בלי הניסיון הכפול המילה הזו לא נתפסת.
    let matchedProtected = false;
    for (const len of [2, 1]) {
      if (word.length <= len) continue;
      const prefix = word.slice(0, len);
      if (!/^[והבלמשכ]+$/.test(prefix)) continue;
      const stem = word.slice(len);
      const stemHit = WORD_MAP.get(stem);
      if (stemHit) {
        const joined = prefix + stemHit[0];
        changes.push({ from: word, to: joined, rule: stemHit[1] });
        return joined;
      }
      if (PROTECTED.has(stem)) matchedProtected = true;
    }
    if (matchedProtected) return word;

    let next = word;
    for (const { re, to, rule } of PATTERNS) {
      re.lastIndex = 0;
      const candidate = next.replace(re, to);
      if (candidate !== next) {
        changes.push({ from: next, to: candidate, rule });
        next = candidate;
      }
    }
    return next;
  });

  return { text: out, changes };
}

/** כמה מילים שונו — לשימוש במדידה ובלוג. */
export function countAshkenaziChanges(text: string): number {
  return normalizeAshkenazi(text).changes.length;
}
