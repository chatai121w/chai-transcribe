# -*- coding: utf-8 -*-
"""מוודא שאיחוד הכתיב תופס כתיב ואינו מסתיר שגיאות.

כל הזוגות כאן נלקחו מתוך מדידה אמיתית על מדגם הבדיקה — אלה
המילים שהמנוע הוציא בפועל מול מה שהיה אמור לצאת. הם מחולקים
לשתי קבוצות:

  אותה מילה      הבדל כתיב בלבד. הכלל חייב לאחד אותן, אחרת
                 אנחנו סופרים כשגיאה משהו שיצא נכון.

  מילים שונות    שגיאה אמיתית של המנוע, או שתי מילים שונות
                 שבמקרה דומות. הכלל אסור לו לאחד אותן —
                 אחרת הציון שלנו מחמיא לעצמו, והמדידה מאבדת
                 את כל ערכה.

הקבוצה השנייה חשובה יותר. כלל רחב מדי גרוע מאין כלל: הוא מעלה
את האחוז בלי שאיכות התמלול השתנתה במאום.
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from hebrew_spelling import normalise_word, same_word, skeleton  # noqa: E402


# ---------------------------------------------- אותה מילה, כתיב אחר
SAME = [
    ("יתכן", "ייתכן"),            # יו"ד כפולה
    ("לעתים", "לעיתים"),
    ("הפרמידה", "הפירמידה"),
    ("אינדיבידואלים", "אינדיבידואליים"),
    ("משלחות", "משלוחות"),        # וי"ו שנוספה
    ("זגרוס", "זאגרוס"),          # אל"ף בשם לועזי
    ("מתוכנן", "מתכנן") ,         # שתי וי"וים
]


# ------------------------------------------ מילים שונות — אסור לאחד
DIFFERENT = [
    ("והיא", "והוא"),       # היא מול הוא — ההבדל המסוכן ביותר
    ("היא", "הוא"),
    ("אל", "את"),
    ("קצת", "קצר"),
    ("מרטלי", "מרקלי"),     # שם פרטי שנשמע לא נכון
    ("אופסלה", "אובסלה"),
    ("יותר", "ביותר"),      # תחילית מוסיפה משמעות
    ("תוך", "בתוך"),
    ("עזים", "העיזים"),     # ה' הידיעה
    ("בשוודיה", "שבשוודיה"),
    ("התפתח", "יתפתח"),     # עבר מול עתיד
    ("קולית", "קולטית"),
    ("התחרתה", "התחרה"),
    ("ספינות", "תנפינות"),
    ("ימי", "ימים"),
    ("בויתו", "בויטו"),     # ת' מול ט' — עיצור, לא כתיב

    # אותם עיצורים ואותו מספר וי"וים, רק במקום אחר. "תקופות" הן
    # זמנים ו"תוקפות" הוא התקפה. זה המקרה שבגללו נדרש התנאי
    # שההבדל יהיה הסרה ולא הזזה.
    ("תקופות", "תוקפות"),
    ("מסוחרים", "מסחורים"),
]


@pytest.mark.parametrize("a,b", SAME)
def test_אותה_מילה_מאוחדת(a, b):
    assert same_word(a, b), "%s ו-%s הן אותה מילה בכתיב אחר" % (a, b)


@pytest.mark.parametrize("a,b", DIFFERENT)
def test_מילים_שונות_אינן_מאוחדות(a, b):
    # זאת הבדיקה שמגינה על אמינות המדידה.
    assert not same_word(a, b), (
        "%s ו-%s הן מילים שונות — איחודן מסתיר שגיאה אמיתית" % (a, b))


def test_מילה_זהה_לעצמה():
    for w in ("שלום", "א", "", "בית"):
        assert same_word(w, w)


def test_אותיות_סופיות_אינן_הבדל():
    assert same_word("ימים", "ימימ")
    assert same_word("שלך", "שלכ")


def test_ניקוד_אינו_הבדל():
    assert same_word("שָׁלוֹם", "שלום")


def test_גרשיים_אינם_הבדל():
    assert same_word('רש"י', "רשי")


def test_שלד_קצר_אינו_מספיק():
    # "הא" הוא שלד של הוא, היא, אה ועוד — קצר מכדי לזהות מילה.
    assert skeleton("הוא") == skeleton("היא")
    assert not same_word("הוא", "היא")


def test_הפרש_אורך_גדול_אינו_כתיב():
    # אותם עיצורים אך פער גדול מדי — זאת מילה אחרת.
    assert not same_word("כתב", "כתוביות")


def test_הנרמול_יציב():
    # אותה מילה חייבת לתת אותו מפתח, אחרת ההשוואה לא תעבוד.
    assert normalise_word("יתכן") == normalise_word("ייתכן")
    assert normalise_word("הוא") != normalise_word("היא")
