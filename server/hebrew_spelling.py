# -*- coding: utf-8 -*-
"""מזהה שתי צורות כתיב של אותה מילה עברית.

הבעיה
-----
בעברית אותה מילה נכתבת ביותר מדרך אחת, וכולן תקינות:

    יתכן   ייתכן          לעתים   לעיתים
    הפרמידה  הפירמידה     אינדיבידואלים  אינדיבידואליים

כשמשווים תמלול להפניה, ההבדל הזה נספר כשגיאה. במדגם הבדיקה שלנו
29 מתוך 77 המילים ה"שגויות" היו מהסוג הזה — המנוע שמע את המילה
נכון לגמרי.

הסכנה
-----
הפיתוי הוא להגדיר "נבדלות באות אחת". זה רחב מדי ומסוכן:

    והיא / והוא      שתי מילים שונות — היא מול הוא
    אל / את          שונות
    קצת / קצר        שונות
    מרטלי / מרקלי    שם פרטי שנשמע לא נכון

כלל רחב מדי גרוע מאין כלל: הוא מסתיר שגיאות אמיתיות ומנפח את
אחוז ההצלחה. מדידה שמחמיאה לעצמה היא מדידה חסרת ערך.

הכלל שנבחר
----------
רק אותיות י' ו-ו' נוספות או נשמטות בכתיב מלא וחסר. שאר האותיות
הן העיצורים, והן אינן משתנות. לכן:

    שתי מילים הן אותה מילה אם הן זהות אחרי הסרת כל האותיות
    י' ו-ו' — ובתנאי שמה שנשאר ארוך מספיק כדי להיות מילה.

תנאי האורך הוא מה שעוצר את "והיא" מול "והוא": שתיהן מצטמצמות
ל"הא", שתי אותיות בלבד, וזה קצר מדי מכדי לזהות מילה.

הכלל נבדק על כל 77 המילים השגויות במדגם: הוא תופס את הבדלי הכתיב
ואינו מאחד אף שגיאה אמיתית. הבדיקה יושבת ב-test_hebrew_spelling.py
ותיפול אם הכלל יורחב בטעות.
"""
from __future__ import annotations

import re
import unicodedata

# אותיות שנכתבות או נשמטות בכתיב מלא וחסר, ורק הן. י' ו-ו' הן
# המקרה השכיח; א' נוספת בשמות לועזיים — "זגרוס" מול "זאגרוס".
# ה' אינה כאן בכוונה: היא גם תחילית וגם עיצור, והוספתה הייתה
# מאחדת "עזים" עם "העיזים" — תחילית, לא כתיב.
MATRES = "יוא"

# אחרי הסרת י' ו-ו', מה שנשאר חייב להיות לפחות באורך הזה.
# שלוש אותיות הוא השורש העברי הטיפוסי. קצר מזה — צירופים רבים
# מדי מצטמצמים לאותו דבר, ובהם מילים שונות באמת.
MIN_SKELETON = 3

NIKUD = re.compile(r"[֑-ׇ]")

FINALS = {"ך": "כ", "ם": "מ", "ן": "נ", "ף": "פ", "ץ": "צ"}


def strip_marks(word):
    """מוריד ניקוד, טעמים וגרשיים, ומאחד אותיות סופיות."""
    w = unicodedata.normalize("NFC", word or "")
    w = NIKUD.sub("", w)
    w = w.replace("׳", "").replace("״", "")
    w = w.replace("'", "").replace('"', "")
    return "".join(FINALS.get(c, c) for c in w)


def skeleton(word):
    """שלד המילה: רק העיצורים, בלי י' ו-ו'."""
    return "".join(c for c in strip_marks(word) if c not in MATRES)


def _is_short_spelling_of(short, full):
    """האם הקצרה מתקבלת מהארוכה בהסרת אמות קריאה בלבד.

    זה התנאי שמבדיל כתיב ממילה אחרת, והוא הכרחי. בלעדיו "תקופות"
    ו"תוקפות" נחשבות זהות: לשתיהן אותם עיצורים ואותו מספר וי"וים,
    רק במקומות שונים. אבל האחת היא זמנים והשנייה היא התקפה, וזאת
    שגיאה אמיתית של המנוע שאסור להסתיר.

    הסרה כן, הזזה לא.
    """
    i = 0
    for c in full:
        if i < len(short) and short[i] == c:
            i += 1
        elif c not in MATRES:
            return False  # עיצור שאינו מופיע בקצרה — מילה אחרת
    return i == len(short)


def same_word(a, b):
    """האם שתי המילים הן אותה מילה בשני כתיבים.

    שלושה תנאים, וכולם נדרשים:

      אותם עיצורים       אחרת זאת פשוט מילה אחרת.
      שלד ארוך מספיק     "הוא" ו"היא" מצטמצמות שתיהן ל"הא".
      הסרה ולא הזזה      "תקופות" ו"תוקפות" — ראה למעלה.
    """
    a, b = strip_marks(a), strip_marks(b)
    if a == b:
        return True
    sa, sb = skeleton(a), skeleton(b)
    if sa != sb or len(sa) < MIN_SKELETON:
        return False
    short, full = (a, b) if len(a) <= len(b) else (b, a)
    if len(full) - len(short) > 2:
        return False
    return _is_short_spelling_of(short, full)


def normalise_word(word):
    """מחזיר צורה אחת קבועה למילה, לשימוש בהשוואה.

    השלד אינו מתאים להצגה למשתמש — הוא חסר אותיות. הוא נועד
    לשמש כמפתח השוואה בלבד, ורק כשהוא ארוך מספיק; אחרת מוחזרת
    המילה עצמה, כדי שמילים קצרות ישוו כרגיל.
    """
    w = strip_marks(word)
    s = skeleton(w)
    return s if len(s) >= MIN_SKELETON else w
